def choose_film_cues(
    probability: float = 0.12,
    count: int = 3,
    excluded: Collection[str] = (),
    rng: random.Random | None = None,
) -> list[FilmQuote]:
    """Randomly pick 2–3 film quotes to offer the LLM as optional flavour.

    Returns an empty list most of the time.  When triggered, draws from the
    full catalogue and excludes recently used quotes.
    """

    if not 0.0 <= probability <= 1.0:
        raise ValueError("probability must be between 0 and 1")
    rng = rng or random
    if rng.random() >= probability:
        return []
    excluded_set = set(excluded)
    pool = [q for q in FILM_QUOTES if q.text not in excluded_set]
    if not pool:
        return []
    k = min(rng.randint(2, 3), len(pool))
    return rng.sample(pool, k=k)


def build_hints(
    cue: PhraseCue | None = None,
    film_cues: Sequence[FilmQuote] = (),
) -> str:
    """Optional per-reply hints: at most one style cue and a film-quote shortlist."""

    parts: list[str] = []
    if cue is not None:
        kind = "редкая характерная цитата" if cue.distinctive else "разговорный оборот"
        parts.append(
            "\n\n## Необязательная стилевая подсказка для этой реплики\n"
            + f"Кандидат ({kind}, категория {cue.category}): «{cue.text}»\n"
            + f"Когда уместно: {cue.usage}\n"
            + "Это не обязательное требование. Используй максимум этот один оборот, только если он естественно подходит по смыслу; иначе полностью проигнорируй."
        )
    if film_cues:
        lines: list[str] = [
            "\n\n## Крылатые фразы из советских фильмов (на выбор)",
            "Ниже даны несколько фраз — ты можешь использовать максимум одну из них, если она органично ложится в ответ и соответствует настроению реплики. Не используй насильно, не объясняй цитату и не указывай фильм в ответе. Если ни одна не подходит — просто проигнорируй.",
        ]
        for i, q in enumerate(film_cues, 1):
            lines.append(
                f"{i}. «{q.text}» — {q.film} ({q.context_hint})"
            )
        parts.append("\n".join(lines))
    return "\n".join(parts)


FINAL_INSTRUCTION = (
    "\n\nНе объясняй наличие подсказок в ответе. Верни только готовую реплику для чата "
    "или ровно SKIP, если отвечать не нужно."
)


def build_system_prompt(
    cue: PhraseCue | None = None,
    film_cues: Sequence[FilmQuote] = (),
    overrides_section: str = "",
) -> str:
    """Build the stable persona prompt with at most one optional style cue
    and an optional shortlist of film quotes for the LLM to optionally use."""

    parts: list[str] = [BASE_SYSTEM_PROMPT]
    hints = build_hints(cue, film_cues)
    if hints:
        parts.append(hints)
    if overrides_section:
        parts.append(overrides_section)
    parts.append(FINAL_INSTRUCTION)
    return "\n".join(parts)
